"""조립 파서 `text/kodate` — 기간·상대 날짜 표현을 표가 아니라 구성 요소로 센다 (2026-10-12).

표로 열거하면 다음 환자가 그 다음 조합을 쓴다(열사흘·스무이틀·그글피·다다다음 주).
여기 케이스는 파서를 만들 때 쓴 43개 + 폰 1.7B 실측 세트.
새 조합이 틀리면 **낱말을 표에 넣지 말고 결합 규칙을 고친다.**
"""

from __future__ import annotations

import pytest

from medimate.text.kodate import find_durations

CASES = [
    # 고유어 날 이름 + 조합
    ("열하루 뒤에 오라고", [11]),
    ("열사흘 후 재방문", [13]),
    ("열엿새 뒤 보자고", [16]),
    ("스무하루 뒤에 오래요", [21]),
    ("스무이틀 뒤에 보자고", [22]),
    ("여드레 뒤에 실밥 뽑으러 오라고", [8]),
    ("아흐레 후 재방문", [9]),
    ("보름 남짓 지나서 오래요", [15]),
    ("열흘쯤 있다가 오래요", [10]),
    ("스무 날 뒤에 보자고", [20]),
    # 상대 낱말
    ("그글피에 다시 오래요", [4]),
    ("내일모레 보자고", [2]),
    ("모레쯤 다시 오라고", [2]),
    ("다담주에 오라고", [14]),
    ("다다다음 주에 재방문", [21]),
    ("담달에 다시 오세요", [30]),
    ("다다음 달에 경과 보자고", [60]),
    ("다음 주 수요일에 오라고", [7]),
    ("달포 뒤에 오라고", [30]),
    ("반년 뒤에 재검", [180]),
    ("내년에 다시 보자고", [365]),
    ("오늘 피검사 했고", [0]),
    # 수사 × 단위 (+ 반)
    ("삼일 뒤에 오라고", [3]),
    ("오일 후 재방문", [5]),
    ("사십일 뒤 재방문", [40]),
    ("일 년 뒤에 보자고", [365]),
    ("일주일 반 뒤에 오래요", [10]),
    ("두 주 반 뒤에 보자고", [17]),
    ("석 달 반 뒤에 재검", [105]),
    ("한 달 반 뒤에 오라고", [45]),
    ("열두 주 뒤에 오라고", [84]),
    ("한 주 정도 있다가 다시 와보래요", [7]),
    ("2주 뒤에 오라고", [14]),
    ("4일후 재방문", [4]),
    ("한달뒤 재방문", [30]),
    ("열흘뒤에보자고", [10]),
    # 한 문장에 여럿 — 순서대로 전부
    ("닷새 정도 약 먹고 보름 뒤에 오라고", [5, 15]),
    ("일주일치 약처방 이주일 후 재방문", [7, 14]),
    ("3일치 약 먹고 다시 오세요", [3]),
    # 복용법의 `하루 N번`은 기간이 아니다. 뒤의 `이틀`만 남는다
    ("하루 두 번 먹고 이틀 뒤에 오라고", [2]),
    ("일주일에 두 번 오라고", [7]),
    # 없는 것
    ("어제부터 아팠어요", []),
    ("안 좋아지면 바로 오래요", []),
]


@pytest.mark.parametrize(("text", "days"), CASES)
def test_durations_are_composed_not_looked_up(text, days):
    assert [d.days for d in find_durations(text)] == days


def test_the_matched_text_is_verbatim_and_positioned():
    t = "닷새 정도 약 먹고 보름 뒤에 오라고"
    ds = find_durations(t)
    assert [(d.text, d.start) for d in ds] == [("닷새", 0), ("보름", t.index("보름"))]
    assert all(t[d.start : d.end] == d.text for d in ds)


def test_point_words_are_marked_so_they_need_no_return_word():
    """모레·담주·다다음 달은 그 자체로 시점. 열흘·두 주는 기간이라 재방문 말이 있어야 한다."""
    assert [d.point for d in find_durations("모레 보자고")] == [True]
    assert [d.point for d in find_durations("다다음 달에")] == [True]
    assert [d.point for d in find_durations("열흘 뒤에")] == [False]
    assert [d.point for d in find_durations("두 주 분")] == [False]
